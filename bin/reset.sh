#!/bin/sh
# ============================================================
#  بازنشانی کامل سایت (حذف دیتابیس + راه‌اندازی مجدد از نو)
#  هشدار: همه سفارش‌ها و محصولات ساخته‌شده حذف می‌شوند!
# ============================================================
set -e
cd "$(dirname "$0")/.."

echo "در حال حذف کانتینرها و دیتابیس ..."
docker compose down -v

echo "ساخت و راه‌اندازی مجدد ..."
docker compose up -d --build

echo ""
echo "صبر کنید تا نصب کامل شود (حدود ۱ تا ۳ دقیقه) ..."
sleep 15
docker compose logs --tail 30 web
echo ""
echo "✅ سایت آماده است: http://localhost:8080"
